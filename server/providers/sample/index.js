// Sample-data provider. Implements the same interface a licensed provider
// adapter must implement (see ../README-providers.md). All output is
// simulated and flagged with `simulated: true` / `sample: true`.

import { buildSampleWorld } from './generator.js';
import { buildSampleOptions } from './options.js';
import { lastCompletedSession, istTimestamp, addDays } from '../../lib/dates.js';

export class SampleProvider {
  constructor({ forceStale = false } = {}) {
    this.id = 'sample';
    this.forceStale = forceStale;
    this._world = null;
    this._worldKey = null;
  }

  world() {
    let end = lastCompletedSession();
    // Optional: simulate stale data to demonstrate the stale-data UI state.
    if (this.forceStale) end = lastCompletedSession(new Date(Date.now() - 6 * 86400000));
    if (this._worldKey !== end) {
      this._world = buildSampleWorld({ endDate: end });
      this._worldKey = end;
    }
    return this._world;
  }

  async describe() {
    const w = this.world();
    const last = w.dates[w.dates.length - 1];
    return {
      id: this.id,
      name: 'Sample data (simulated)',
      dataMode: 'sample',
      simulated: true,
      delayMinutes: null,
      asOf: istTimestamp(last, '15:30'),
      licenseNote: 'All companies, prices, news, events and estimates in this mode are fictional and generated by the app. They are not market data.',
    };
  }

  async listInstruments() {
    const w = this.world();
    return Object.values(w.companies).map(({ profile: p }) => ({
      ticker: p.ticker, name: p.name, exchanges: p.exchanges, sector: p.sector, currency: 'INR', simulated: true,
    }));
  }

  async getBars(ticker) {
    const c = this.world().companies[ticker];
    return c ? c.bars : null;
  }

  async getQuote(ticker) {
    const w = this.world();
    const c = w.companies[ticker];
    if (!c) return null;
    const b = c.bars;
    const last = b[b.length - 1];
    const prev = b[b.length - 2];
    return {
      ticker, price: last.close, previousClose: prev.close, change: +(last.close - prev.close).toFixed(2),
      changePct: +((last.close / prev.close - 1) * 100).toFixed(2), currency: 'INR',
      asOf: istTimestamp(last.date, '15:30'), freshness: 'sample', simulated: true,
      exchange: c.profile.exchanges[0], source: 'Sample Market Data (simulated)',
    };
  }

  async getFundamentals(ticker) {
    const c = this.world().companies[ticker];
    return c ? c.fundamentals : null;
  }

  async getNews({ ticker, sector, scopes } = {}) {
    const all = this.world().news;
    return all
      .filter((x) => {
        if (scopes && !scopes.includes(x.scope)) return false;
        if (x.scope === 'company') return ticker ? x.tickers.includes(ticker) : !sector || x.sector === sector;
        if (x.scope === 'sector') return !sector || x.sector === sector;
        return true;
      })
      .sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : -1));
  }

  async getCalendar({ from, to } = {}) {
    const w = this.world();
    const start = from || w.dates[w.dates.length - 1];
    const end = to || addDays(start, 60);
    return w.calendar.filter((e) => e.date >= start && e.date <= end).sort((a, b) => (a.date < b.date ? -1 : 1));
  }

  async getMacro() {
    return this.world().macro;
  }

  async getEstimates(ticker) {
    return this.world().estimates[ticker] || null;
  }

  async getSourceItem(id) {
    const w = this.world();
    return w.news.find((x) => x.id === id) || w.calendar.find((x) => x.id === id) || null;
  }

  options() {
    const w = this.world();
    if (this._optWorld !== w) { this._opt = buildSampleOptions(w); this._optWorld = w; }
    return this._opt;
  }

  /** Underlyings with listed options (F&O segment). */
  async getOptionUnderlyings() {
    return Object.values(this.options()).map(({ rows, history, ...u }) => u);
  }

  /** Full end-of-day option chain for one underlying, plus ATM IV / PCR history. */
  async getOptionChain(symbol) {
    return this.options()[symbol] || null;
  }

  async sessions() {
    return this.world().dates;
  }
}
