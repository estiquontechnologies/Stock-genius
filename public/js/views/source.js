import { api } from '../api.js';
import { html, fmt, kindBadge } from '../ui.js';

export async function render(el, [id]) {
  const { item } = await api(`/api/sources/${encodeURIComponent(id)}`);
  el.innerHTML = String(html`<div class="card" style="max-width:760px">
    <div class="row">${item.sample ? kindBadge('sample') : kindBadge('fact')}<span class="small muted">${item.source} · ${fmt.datetime(item.publishedAt || item.date)}</span></div>
    <h1 style="margin-top:10px">${item.headline || item.title}</h1>
    ${item.sample ? html`<div class="callout warn" style="margin-top:12px"><b>This is a simulated item.</b> It was generated by the app’s sample-data mode to demonstrate features. It is not a real announcement, filing or news report, and no real company is described.</div>` : ''}
    ${item.facts?.length ? html`<h3 style="margin-top:16px">Reported facts</h3><ul class="bullet">${item.facts.map((f) => html`<li>${f}</li>`)}</ul>` : ''}
    ${item.note ? html`<p class="small muted">${item.note}</p>` : ''}
    ${item.tickers?.length ? html`<p class="small">Related: ${item.tickers.map((t) => html`<a href="#/stock/${t}">${t}</a> `)}</p>` : ''}
    <p style="margin-top:16px"><button class="btn sm" data-back>← Back</button></p></div>`);
  el.querySelector('[data-back]').addEventListener('click', () => history.back());
}
