// Rendering helpers. All dynamic text goes through esc() / html`` to prevent XSS.

export const esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

class Raw { constructor(s) { this.s = s; } toString() { return this.s; } }
export const raw = (s) => new Raw(s);

/** Tagged template: interpolations are escaped unless wrapped in raw() or arrays of html. */
export function html(strings, ...vals) {
  let out = '';
  strings.forEach((s, i) => {
    out += s;
    if (i < vals.length) out += flatten(vals[i]);
  });
  return new Raw(out);
}
function flatten(v) {
  if (v == null || v === false) return '';
  if (v instanceof Raw) return v.s;
  if (Array.isArray(v)) return v.map(flatten).join('');
  return esc(v);
}

export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

// ---------------------------------------------------------------- format
const inrFmt = new Intl.NumberFormat('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const intFmt = new Intl.NumberFormat('en-IN', { maximumFractionDigits: 0 });
export const fmt = {
  inr: (x, d = 2) => (x == null || !Number.isFinite(x) ? '—' : `₹${d === 0 ? intFmt.format(x) : inrFmt.format(x)}`),
  num: (x, d = 1) => (x == null || !Number.isFinite(x) ? '—' : Number(x).toLocaleString('en-IN', { minimumFractionDigits: d, maximumFractionDigits: d })),
  pct: (x, d = 1) => (x == null || !Number.isFinite(x) ? '—' : `${x >= 0 ? '+' : '−'}${Math.abs(x * 100).toFixed(d)}%`),
  pctAbs: (x, d = 1) => (x == null || !Number.isFinite(x) ? '—' : `${(x * 100).toFixed(d)}%`),
  pp: (x, d = 2) => (x == null || !Number.isFinite(x) ? '—' : `${x >= 0 ? '+' : '−'}${Math.abs(x).toFixed(d)}%`),
  cr: (x) => (x == null || !Number.isFinite(x) ? '—' : `₹${intFmt.format(Math.round(x))} cr`),
  date: (iso) => {
    if (!iso) return '—';
    const d = new Date(iso.length === 10 ? `${iso}T12:00:00+05:30` : iso);
    return d.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'Asia/Kolkata' });
  },
  datetime: (iso) => {
    if (!iso) return '—';
    const d = new Date(iso);
    return `${d.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'Asia/Kolkata' })}, ${d.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', timeZone: 'Asia/Kolkata' })} IST`;
  },
};
export const tone = (x) => (x == null ? '' : x > 0 ? 'up' : x < 0 ? 'down' : '');

// ------------------------------------------------------------ components
export function viewBadge(view, lg = false) {
  const icon = { Buy: '▲', Hold: '■', Sell: '▼' }[view] || '';
  return html`<span class="view ${view} ${lg ? 'lg' : ''}"><span aria-hidden="true">${icon}</span>${view}</span>`;
}

export function freshnessBadge(f, asOf) {
  const map = { sample: ['sample', 'Sample data'], eod: ['eod', 'End-of-day'], live: ['live', 'Live'], delayed: ['delayed', 'Delayed'], stale: ['stale', 'Stale'] };
  const [cls, label] = map[f] || ['neutral', f || 'Unknown'];
  return html`<span class="badge ${cls}" title="${asOf ? `Data as of ${fmt.datetime(asOf)}` : ''}">${label}</span>`;
}

export const kindBadge = (k) => ({
  fact: html`<span class="badge fact" title="Data reported by a source">Fact</span>`,
  analysis: html`<span class="badge analysis" title="Interpretation generated by the model — not a fact">Analysis</span>`,
  user: html`<span class="badge user" title="Information you entered">Your input</span>`,
  sample: html`<span class="badge sample" title="Simulated demonstration data — not real">Sample</span>`,
}[k]);

export function confMeter(conf) {
  const on = Math.round((conf / 100) * 5);
  return html`<span class="conf-meter" role="img" aria-label="Confidence ${conf} out of 100">${[0, 1, 2, 3, 4].map((i) => html`<i class="${i < on ? 'on' : ''}"></i>`)}</span>`;
}

export const explain = (term, label = 'Explain') => html`<button type="button" class="explain" data-term="${term}" aria-label="Explain ${term.replace(/-/g, ' ')}">ⓘ ${label}</button>`;

export function dirBar(score) {
  const w = Math.min(50, Math.abs(score) * 50);
  const style = score >= 0 ? `left:50%;width:${w}%;background:var(--up)` : `right:50%;width:${w}%;background:var(--down)`;
  return html`<span class="dirbar" role="img" aria-label="Signal score ${score.toFixed(2)} (${score > 0 ? 'positive' : score < 0 ? 'negative' : 'neutral'})"><span style="${style}"></span></span>`;
}

export function skeleton(lines = 6) {
  return html`<div class="stack" aria-busy="true" aria-label="Loading">${Array.from({ length: lines }, (_, i) => html`<div class="skeleton" style="height:${i === 0 ? 34 : 18}px;width:${[60, 100, 92, 96, 80, 70][i % 6]}%"></div>`)}</div>`;
}

export function pageSkeleton() {
  return html`<div class="stack"><div class="skeleton" style="height:36px;width:40%"></div><div class="grid cols-3">${[1, 2, 3].map(() => html`<div class="card">${skeleton(4)}</div>`)}</div><div class="card">${skeleton(8)}</div></div>`;
}

export function emptyState(title, body, action) {
  return html`<div class="empty"><svg width="40" height="40" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><path d="M3 17l5-5 4 4 8-9"/></svg><h3>${title}</h3><p>${body}</p>${action || ''}</div>`;
}

export function errorState(err, retry = true) {
  if (err?.code === 'not_ready') {
    const c = err.body?.collector;
    return html`<div class="card"><div class="empty"><h3>Market data is being collected</h3><p>${err.message}</p>
      ${c ? html`<p class="small">Sessions stored: ${c.sessionsStored ?? 0} · Last run: ${c.lastRunFinished ? fmt.datetime(c.lastRunFinished) : 'in progress'}${c.running ? ' · running now' : ''}</p>` : ''}
      <button class="btn" data-action="retry">Check again</button></div></div>`;
  }
  return html`<div class="error-box" role="alert"><h3>We couldn’t load this</h3><p>${err?.message || 'Unexpected error.'}</p>${retry ? html`<button class="btn sm" data-action="retry">Try again</button>` : ''}</div>`;
}

export function toast(msg) {
  const el = document.createElement('div');
  el.className = 'toast';
  el.setAttribute('role', 'status');
  el.textContent = msg;
  document.body.appendChild(el);
  setTimeout(() => el.remove(), 2600);
}

export function sourceLine(src) {
  if (!src) return '';
  const name = typeof src === 'string' ? src : src.name;
  return html`<div class="source-line">Source: ${name}${src.asOf ? html` · as of ${fmt.datetime(src.asOf)}` : ''}${src.note ? html` · ${src.note}` : ''}</div>`;
}

export function newsLink(item) {
  const internal = item.url?.startsWith('#');
  return html`<a href="${item.url}" ${internal ? '' : raw('target="_blank" rel="noopener noreferrer nofollow"')}>${item.headline}</a>`;
}

export const sectorLink = (s) => html`<a href="#/explore?sector=${encodeURIComponent(s)}">${s}</a>`;
